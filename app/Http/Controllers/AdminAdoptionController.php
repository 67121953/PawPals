<?php

namespace App\Http\Controllers;

use App\Models\Adoption;
use App\Models\Conversation;
use App\Models\Message;
use App\Models\User;
use Illuminate\Support\Facades\DB;

class AdminAdoptionController extends Controller
{
    /*
    |--------------------------------------------------------------------------
    | รายการคำขอรับเลี้ยง
    |--------------------------------------------------------------------------
    */

    public function index()
    {
        $adoptions = Adoption::with('pet')
            ->latest()
            ->paginate(10);

        return view(
            'admin.adoptions.index',
            compact('adoptions')
        );
    }


    /*
    |--------------------------------------------------------------------------
    | รายละเอียดคำขอ
    |--------------------------------------------------------------------------
    */

    public function show(Adoption $adoption)
    {
        $adoption->load('pet');

        return view(
            'admin.adoptions.show',
            compact('adoption')
        );
    }


    /*
    |--------------------------------------------------------------------------
    | อนุมัติการรับเลี้ยง
    |--------------------------------------------------------------------------
    */

    public function approve(Adoption $adoption)
    {
        /*
        |--------------------------------------------------------------------------
        | ตรวจสอบสถานะคำขอ
        |--------------------------------------------------------------------------
        */

        if ($adoption->status !== 'pending') {

            return back()->with(
                'error',
                'คำขอนี้ถูกจัดการไปแล้ว'
            );
        }


        /*
        |--------------------------------------------------------------------------
        | ตรวจสอบสัตว์เลี้ยง
        |--------------------------------------------------------------------------
        */

        $pet = $adoption->pet;

        if (
            !$pet ||
            $pet->adoption_status !== 'pending'
        ) {

            return back()->with(
                'error',
                'สถานะสัตว์เลี้ยงไม่ถูกต้อง'
            );
        }


        /*
        |--------------------------------------------------------------------------
        | อนุมัติ + ส่งข้อความ Chat
        |--------------------------------------------------------------------------
        */

        DB::transaction(function () use ($adoption, $pet) {

            /*
            |--------------------------------------------------------------------------
            | เปลี่ยนสถานะ Adoption
            |--------------------------------------------------------------------------
            */

            $adoption->update([
                'status' => 'approved',
            ]);


            /*
            |--------------------------------------------------------------------------
            | เปลี่ยนสถานะสัตว์เลี้ยง
            |--------------------------------------------------------------------------
            */

            $pet->update([
                'adoption_status' => 'adopted',
            ]);


            /*
            |--------------------------------------------------------------------------
            | หา User จาก Email
            |--------------------------------------------------------------------------
            |
            | Adoption ของระบบปัจจุบันไม่มี user_id
            | จึงใช้ email จากใบสมัครค้นหา User
            |
            */

            $user = User::where(
                'email',
                $adoption->email
            )->first();


            /*
            |--------------------------------------------------------------------------
            | ถ้าพบ User ให้สร้างข้อความใน Chat
            |--------------------------------------------------------------------------
            */

            if ($user) {

                /*
                |--------------------------------------------------------------------------
                | หา Conversation ของ User
                |--------------------------------------------------------------------------
                */

                $conversation = Conversation::firstOrCreate([
                    'user_id' => $user->id,
                ]);


                /*
                |--------------------------------------------------------------------------
                | สร้างข้อความแจ้งเตือน
                |--------------------------------------------------------------------------
                */

                Message::create([
                    'conversation_id' => $conversation->id,

                    /*
                     * ผู้ส่งคือ Admin ที่กำลังกดอนุมัติ
                     */
                    'sender_id' => auth()->id(),

                    'message' =>
                        "🐾 การรับเลี้ยงได้รับการอนุมัติแล้ว!\n\n" .
                        "แอดมินอนุมัติคำขอรับเลี้ยงของคุณเรียบร้อยแล้ว\n\n" .
                        "สัตว์เลี้ยงที่คุณเลือกรับเลี้ยง: " .
                        $pet->name .
                        "\n\n" .
                        "ขอบคุณที่เลือก PawPals ❤️",
                ]);


                /*
                |--------------------------------------------------------------------------
                | อัปเดต Conversation
                |--------------------------------------------------------------------------
                */

                $conversation->touch();
            }
        });


        /*
        |--------------------------------------------------------------------------
        | กลับหน้ารายละเอียด
        |--------------------------------------------------------------------------
        */

        return redirect()
            ->route(
                'admin.adoptions.show',
                $adoption
            )
            ->with(
                'success',
                'อนุมัติคำขอรับเลี้ยงเรียบร้อยแล้ว'
            );
    }


    /*
    |--------------------------------------------------------------------------
    | ปฏิเสธการรับเลี้ยง
    |--------------------------------------------------------------------------
    */

    public function reject(Adoption $adoption)
    {
        /*
        |--------------------------------------------------------------------------
        | ตรวจสอบสถานะคำขอ
        |--------------------------------------------------------------------------
        */

        if ($adoption->status !== 'pending') {

            return back()->with(
                'error',
                'คำขอนี้ถูกจัดการไปแล้ว'
            );
        }


        /*
        |--------------------------------------------------------------------------
        | ดึงสัตว์เลี้ยง
        |--------------------------------------------------------------------------
        */

        $pet = $adoption->pet;


        /*
        |--------------------------------------------------------------------------
        | ปฏิเสธ + ส่งข้อความ Chat
        |--------------------------------------------------------------------------
        */

        DB::transaction(function () use ($adoption, $pet) {

            /*
            |--------------------------------------------------------------------------
            | เปลี่ยนสถานะ Adoption
            |--------------------------------------------------------------------------
            */

            $adoption->update([
                'status' => 'rejected',
            ]);


            /*
            |--------------------------------------------------------------------------
            | ถ้าสัตว์เลี้ยงยังเป็น pending
            | ให้กลับมาเป็น available
            |--------------------------------------------------------------------------
            */

            if (
                $pet &&
                $pet->adoption_status === 'pending'
            ) {

                $pet->update([
                    'adoption_status' => 'available',
                ]);
            }


            /*
            |--------------------------------------------------------------------------
            | หา User จาก Email
            |--------------------------------------------------------------------------
            */

            $user = User::where(
                'email',
                $adoption->email
            )->first();


            /*
            |--------------------------------------------------------------------------
            | ถ้าพบ User ให้ส่งข้อความ Chat
            |--------------------------------------------------------------------------
            */

            if ($user) {

                /*
                |--------------------------------------------------------------------------
                | หา Conversation
                |--------------------------------------------------------------------------
                */

                $conversation = Conversation::firstOrCreate([
                    'user_id' => $user->id,
                ]);


                /*
                |--------------------------------------------------------------------------
                | สร้างข้อความแจ้งเตือน
                |--------------------------------------------------------------------------
                */

                Message::create([
                    'conversation_id' => $conversation->id,

                    /*
                     * ผู้ส่งคือ Admin
                     */
                    'sender_id' => auth()->id(),

                    'message' =>
                        "❌ คำขอรับเลี้ยงไม่ได้รับการอนุมัติ\n\n" .
                        "แอดมินได้ตรวจสอบคำขอรับเลี้ยงของคุณแล้ว\n\n" .
                        "สัตว์เลี้ยงที่คุณเลือก: " .
                        ($pet->name ?? 'ไม่ทราบชื่อ') .
                        "\n\n" .
                        "หากมีข้อสงสัย สามารถสอบถามผ่าน Chat ได้ครับ",
                ]);


                /*
                |--------------------------------------------------------------------------
                | อัปเดตเวลา Conversation
                |--------------------------------------------------------------------------
                */

                $conversation->touch();
            }
        });


        /*
        |--------------------------------------------------------------------------
        | กลับหน้ารายละเอียด
        |--------------------------------------------------------------------------
        */

        return redirect()
            ->route(
                'admin.adoptions.show',
                $adoption
            )
            ->with(
                'success',
                'ปฏิเสธคำขอรับเลี้ยงเรียบร้อยแล้ว'
            );
    }
}