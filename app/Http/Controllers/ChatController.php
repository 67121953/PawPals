<?php

namespace App\Http\Controllers;

use App\Models\Conversation;
use App\Models\Message;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\Auth;

class ChatController extends Controller
{
    /*
    |--------------------------------------------------------------------------
    | ตรวจสอบว่าเป็น Admin หรือไม่
    |--------------------------------------------------------------------------
    */

    private function isAdmin(): bool
    {
        return Auth::user()?->role === 'admin';
    }


    /*
    |--------------------------------------------------------------------------
    | Conversation ของ User ปัจจุบัน
    |--------------------------------------------------------------------------
    |
    | User 1 คน จะมี Conversation หลัก 1 รายการ
    |
    | Conversation นี้ไม่ได้ผูกกับ Admin คนใดคนหนึ่ง
    |
    | ดังนั้น Admin ทุกคนสามารถเข้ามาดูและตอบได้
    |
    */

    private function conversationForUser(): Conversation
    {
        return Conversation::firstOrCreate([
            'user_id' => Auth::id(),
        ]);
    }


    /*
    |--------------------------------------------------------------------------
    | เปิด Chat
    |--------------------------------------------------------------------------
    |
    | Admin:
    |     เห็น Conversation ของ User ทุกคน
    |
    | User:
    |     เห็น Conversation ของตัวเอง
    |
    */

    public function index()
    {

        /*
        |--------------------------------------------------------------------------
        | Admin ทุกคน
        |--------------------------------------------------------------------------
        */

        if ($this->isAdmin()) {

            $conversations = Conversation::with([
                    'user',
                    'latestMessage',
                ])
                ->withCount([
                    'messages as unread_count' => function ($query) {

                        $query
                            ->whereNull('read_at')
                            ->where(
                                'sender_id',
                                '!=',
                                Auth::id()
                            );

                    },
                ])
                ->latest('updated_at')
                ->get();


            return response()->json([

                'admin' => true,

                /*
                |--------------------------------------------------------------------------
                | Admin คนไหน Login เข้ามา
                | ก็จะเห็น Conversation ของ User ทุกคน
                |--------------------------------------------------------------------------
                */

                'conversations' => $conversations,

            ]);
        }


        /*
        |--------------------------------------------------------------------------
        | User ทั่วไป
        |--------------------------------------------------------------------------
        */

        $conversation = $this->conversationForUser();


        $messages = $conversation
            ->messages()
            ->with('sender:id,name,email,role')
            ->orderBy('id')
            ->get();


        /*
        |--------------------------------------------------------------------------
        | เมื่อ User เปิด Chat
        | ให้ข้อความจาก Admin ถูกอ่านแล้ว
        |--------------------------------------------------------------------------
        */

        $conversation
            ->messages()
            ->where('sender_id', '!=', Auth::id())
            ->whereNull('read_at')
            ->update([
                'read_at' => now(),
            ]);


        return response()->json([

            'admin' => false,

            'conversation' => $conversation->load('user'),

            'messages' => $messages,

        ]);
    }


    /*
    |--------------------------------------------------------------------------
    | ดึงข้อความของ Conversation
    |--------------------------------------------------------------------------
    */

    public function messages(Request $request)
    {
        $user = Auth::user();


        $conversationId = $request->get('conversation_id');


        /*
        |--------------------------------------------------------------------------
        | ตรวจสอบ Conversation
        |--------------------------------------------------------------------------
        */

        if (!$conversationId) {

            return response()->json([

                'success' => false,

                'message' => 'ไม่พบ Conversation',

            ], 400);
        }


        $conversation = Conversation::findOrFail(
            $conversationId
        );


        /*
        |--------------------------------------------------------------------------
        | ตรวจสอบสิทธิ์
        |--------------------------------------------------------------------------
        |
        | Admin ทุกคน:
        |     ดูได้ทุก Conversation
        |
        | User:
        |     ดูได้เฉพาะ Conversation ของตัวเอง
        |
        */

        if (
            !$this->isAdmin() &&
            $conversation->user_id !== $user->id
        ) {

            return response()->json([

                'success' => false,

                'message' => 'ไม่มีสิทธิ์เข้าถึงบทสนทนานี้',

            ], 403);
        }


        /*
        |--------------------------------------------------------------------------
        | ดึงข้อความ
        |--------------------------------------------------------------------------
        */

        $messages = $conversation
            ->messages()
            ->with('sender:id,name,email,role')
            ->orderBy('id')
            ->get();


        /*
        |--------------------------------------------------------------------------
        | ทำเครื่องหมายว่าอ่านแล้ว
        |--------------------------------------------------------------------------
        */

        $conversation
            ->messages()
            ->where(
                'sender_id',
                '!=',
                $user->id
            )
            ->whereNull('read_at')
            ->update([
                'read_at' => now(),
            ]);


        return response()->json([

            'success' => true,

            'conversation' => $conversation->load('user'),

            'messages' => $messages,

        ]);
    }


    /*
    |--------------------------------------------------------------------------
    | ดึง Conversation รายตัว
    |--------------------------------------------------------------------------
    |
    | ใช้สำหรับ Admin เลือก User แต่ละคน
    |
    */

    public function conversation(Conversation $conversation)
    {

        /*
        |--------------------------------------------------------------------------
        | Admin ทุกคนดูได้
        | User ดูได้เฉพาะของตัวเอง
        |--------------------------------------------------------------------------
        */

        abort_unless(

            $this->isAdmin() ||
            $conversation->user_id === Auth::id(),

            403

        );


        /*
        |--------------------------------------------------------------------------
        | ดึงข้อความ
        |--------------------------------------------------------------------------
        */

        $messages = $conversation
            ->messages()
            ->with('sender:id,name,email,role')
            ->orderBy('id')
            ->get();


        /*
        |--------------------------------------------------------------------------
        | ทำเครื่องหมายว่าอ่านแล้ว
        |--------------------------------------------------------------------------
        */

        $conversation
            ->messages()
            ->where(
                'sender_id',
                '!=',
                Auth::id()
            )
            ->whereNull('read_at')
            ->update([
                'read_at' => now(),
            ]);


        return response()->json([

            'success' => true,

            'conversation' => $conversation->load('user'),

            'messages' => $messages,

        ]);
    }


    /*
    |--------------------------------------------------------------------------
    | ส่งข้อความ
    |--------------------------------------------------------------------------
    |
    | User:
    |     ส่งเข้า Conversation ของตัวเอง
    |
    | Admin:
    |     เลือก Conversation ของ User
    |     แล้วตอบกลับ
    |
    | สำคัญ:
    |     Admin ไม่ได้ถูกระบุเป็นรายบุคคล
    |     Admin ทุกคนสามารถตอบ Conversation เดียวกันได้
    |
    */

    public function send(Request $request)
    {

        /*
        |--------------------------------------------------------------------------
        | Validate
        |--------------------------------------------------------------------------
        */

        $validated = $request->validate([

            'message' => [
                'required',
                'string',
                'max:5000',
            ],

            'conversation_id' => [
                'nullable',
                'integer',
                'exists:conversations,id',
            ],

        ]);


        /*
        |--------------------------------------------------------------------------
        | Admin
        |--------------------------------------------------------------------------
        */

        if ($this->isAdmin()) {

            /*
            |--------------------------------------------------------------------------
            | Admin ต้องเลือก Conversation ของ User
            |--------------------------------------------------------------------------
            */

            if (empty($validated['conversation_id'])) {

                return response()->json([

                    'success' => false,

                    'message' => 'กรุณาเลือกผู้ติดต่อ',

                ], 422);
            }


            /*
            |--------------------------------------------------------------------------
            | Admin สามารถตอบ Conversation ของ User คนใดก็ได้
            |--------------------------------------------------------------------------
            */

            $conversation = Conversation::findOrFail(
                $validated['conversation_id']
            );
        }


        /*
        |--------------------------------------------------------------------------
        | User ทั่วไป
        |--------------------------------------------------------------------------
        */

        else {

            /*
            |--------------------------------------------------------------------------
            | User ส่งได้เฉพาะ Conversation ของตัวเอง
            |--------------------------------------------------------------------------
            */

            $conversation = $this->conversationForUser();
        }


        /*
        |--------------------------------------------------------------------------
        | สร้างข้อความ
        |--------------------------------------------------------------------------
        */

        $message = $conversation
            ->messages()
            ->create([

                'sender_id' => Auth::id(),

                'message' => trim(
                    $validated['message']
                ),

            ]);


        /*
        |--------------------------------------------------------------------------
        | อัปเดต Conversation
        |--------------------------------------------------------------------------
        */

        $conversation->touch();


        /*
        |--------------------------------------------------------------------------
        | โหลดข้อมูลผู้ส่ง
        |--------------------------------------------------------------------------
        */

        $message->load(
            'sender:id,name,email,role'
        );


        return response()->json([

            'success' => true,

            'message' => $message,

        ]);
    }


    /*
    |--------------------------------------------------------------------------
    | ส่งข้อความจากหน้า Contact
    |--------------------------------------------------------------------------
    |
    | ข้อความจะถูกส่งเข้า Conversation ของ User
    |
    | ไม่ระบุ Admin คนใดคนหนึ่ง
    |
    | Admin ทุกคนสามารถเห็นข้อความนี้ได้
    |
    */

    public function sendContact(Request $request)
    {

        /*
        |--------------------------------------------------------------------------
        | Validate
        |--------------------------------------------------------------------------
        */

        $validated = $request->validate([

            'message' => [
                'required',
                'string',
                'max:5000',
            ],

        ]);


        /*
        |--------------------------------------------------------------------------
        | หา Conversation ของ User
        |--------------------------------------------------------------------------
        */

        $conversation = $this->conversationForUser();


        /*
        |--------------------------------------------------------------------------
        | สร้างข้อความ
        |--------------------------------------------------------------------------
        */

        $message = $conversation
            ->messages()
            ->create([

                'sender_id' => Auth::id(),

                'message' => trim(
                    $validated['message']
                ),

            ]);


        /*
        |--------------------------------------------------------------------------
        | อัปเดตเวลา Conversation
        |--------------------------------------------------------------------------
        */

        $conversation->touch();


        /*
        |--------------------------------------------------------------------------
        | กลับหน้า Contact
        |--------------------------------------------------------------------------
        */

        return redirect()
            ->route('contact')
            ->with(
                'success',
                'ส่งข้อความเรียบร้อยแล้ว ข้อความของคุณถูกส่งถึงทีม Admin ทุกคนแล้ว'
            );
    }


    /*
    |--------------------------------------------------------------------------
    | จำนวนข้อความที่ยังไม่ได้อ่าน
    |--------------------------------------------------------------------------
    |
    | Admin:
    |     นับข้อความใหม่จาก User ทุกคน
    |
    | User:
    |     นับข้อความใหม่จาก Admin
    |
    */

    public function unread()
    {

        /*
        |--------------------------------------------------------------------------
        | Admin ทุกคน
        |--------------------------------------------------------------------------
        */

        if ($this->isAdmin()) {

            $count = Message::whereNull('read_at')
                ->where(
                    'sender_id',
                    '!=',
                    Auth::id()
                )
                ->whereHas('conversation')
                ->count();
        }


        /*
        |--------------------------------------------------------------------------
        | User ทั่วไป
        |--------------------------------------------------------------------------
        */

        else {

            $conversation = Conversation::where(
                'user_id',
                Auth::id()
            )->first();


            $count = $conversation

                ? $conversation
                    ->messages()
                    ->whereNull('read_at')
                    ->where(
                        'sender_id',
                        '!=',
                        Auth::id()
                    )
                    ->count()

                : 0;
        }


        return response()->json([

            'count' => $count,

        ]);
    }


    /*
    |--------------------------------------------------------------------------
    | ทำเครื่องหมายว่าอ่านแล้ว
    |--------------------------------------------------------------------------
    */

    public function markAsRead(Request $request)
    {

        /*
        |--------------------------------------------------------------------------
        | Validate
        |--------------------------------------------------------------------------
        */

        $validated = $request->validate([

            'conversation_id' => [
                'required',
                'integer',
                'exists:conversations,id',
            ],

        ]);


        /*
        |--------------------------------------------------------------------------
        | หา Conversation
        |--------------------------------------------------------------------------
        */

        $conversation = Conversation::findOrFail(
            $validated['conversation_id']
        );


        /*
        |--------------------------------------------------------------------------
        | ตรวจสอบสิทธิ์
        |--------------------------------------------------------------------------
        |
        | Admin ทุกคนสามารถ Mark Read ได้
        |
        | User อ่านได้เฉพาะ Conversation ของตัวเอง
        |
        */

        abort_unless(

            $this->isAdmin() ||
            $conversation->user_id === Auth::id(),

            403

        );


        /*
        |--------------------------------------------------------------------------
        | เปลี่ยนสถานะข้อความ
        |--------------------------------------------------------------------------
        */

        $conversation
            ->messages()
            ->whereNull('read_at')
            ->where(
                'sender_id',
                '!=',
                Auth::id()
            )
            ->update([
                'read_at' => now(),
            ]);


        return response()->json([

            'success' => true,

        ]);
    }
}